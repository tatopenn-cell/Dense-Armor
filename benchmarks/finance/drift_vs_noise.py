"""Benchmark: raw against noise-robust, on a synthetic tick stream.

The pipeline of :mod:`pipelines.finance.drift_vs_noise` runs on two
kinds of stream: one with no shift, where the metric is the alarm
episodes per hour, and one with a planted shift of the drift, where the
metric is the detection delay in ticks. Twenty seeds, median and
interquartile range; the comparison raw against robust carries a paired
Wilcoxon p-value and the A12 effect size.

The stream is synthetic: it is generated by
:func:`pipelines.finance.drift_vs_noise.synthetic_tick`, and the page
that shows the table says so.

The delay comparison imputes ``N_TICKS`` for a seed on which the raw
detector does not fire at all after the shift. The imputation is
declared here: "no alarm after the shift" is a delay larger than the
stream, and ``N_TICKS`` is a lower bound of it. Without the
imputation the raw side has no value on those seeds and the paired
Wilcoxon has no pair. The detection rate (seeds on which the detector
fires after the shift) is reported next to the delay, so the reader
sees the imputation.

Run from the repository root:

    python benchmarks/finance/drift_vs_noise.py
    python benchmarks/finance/drift_vs_noise.py --smoke
"""

from __future__ import annotations

import argparse
import json
import sys
import time
from pathlib import Path

import numpy as np
from scipy.stats import wilcoxon

ROOT = Path(__file__).resolve().parents[2]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

from pipelines.finance.drift_vs_noise import (
    DriftVsNoisePipeline,
    synthetic_tick,
)

N_TICKS = 5000
CHANGE_AT = 2500
TICKS_PER_HOUR = 3600
N_SEEDS = 20
SMOKE_SEEDS = 2


def _a12(a: np.ndarray, b: np.ndarray) -> float:
    """A12 effect size: P(a > b) + 0.5 * P(a == b)."""
    diff = a[:, None] - b[None, :]
    return float((diff > 0).mean() + 0.5 * (diff == 0).mean())


def _wilcoxon(a: np.ndarray, b: np.ndarray) -> float:
    try:
        return float(wilcoxon(a, b).pvalue)
    except ValueError:
        return 1.0


def _one_run(seed: int, shift: bool, noise_df: float) -> dict:
    _, tick = synthetic_tick(
        n=N_TICKS, seed=seed, noise_std=0.005, vol=0.001,
        shift_at=CHANGE_AT if shift else None,
        drift_after=0.002 if shift else 0.0,
        noise_kind="student", noise_df=noise_df,
    )
    pipe = DriftVsNoisePipeline(window=10, warmup=20)
    r = pipe.run(tick, change_at=CHANGE_AT if shift else None)
    return {
        "seed": seed,
        "raw_episodes": r.n_episodes_raw,
        "robust_episodes": r.n_episodes_robust,
        "raw_delay": r.delay_raw_samples,
        "robust_delay": r.delay_robust_samples,
    }


def _summary(values: list[float | None]) -> dict:
    v = np.asarray([x for x in values if x is not None], dtype=float)
    if v.size == 0:
        return {"median": None, "iqr": None, "n": 0}
    return {
        "median": float(np.median(v)),
        "iqr": float(np.percentile(v, 75) - np.percentile(v, 25)),
        "n": int(v.size),
    }


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--smoke", action="store_true",
                    help="only the first two seeds")
    ap.add_argument("--noise-df", type=float, default=3.0,
                    help="degrees of freedom of the Student-t noise")
    ap.add_argument("--out", type=Path, default=None)
    args = ap.parse_args()
    n_seeds = SMOKE_SEEDS if args.smoke else N_SEEDS
    t0 = time.time()
    calm = [_one_run(s, shift=False, noise_df=args.noise_df)
            for s in range(n_seeds)]
    shifted = [_one_run(s, shift=True, noise_df=args.noise_df)
               for s in range(n_seeds)]
    dt = time.time() - t0

    # calm: alarm episodes per hour of normal data
    raw_calm = np.asarray([c["raw_episodes"] for c in calm], dtype=float)
    rob_calm = np.asarray([c["robust_episodes"] for c in calm], dtype=float)
    hours = N_TICKS / TICKS_PER_HOUR
    raw_per_hour = raw_calm / hours
    rob_per_hour = rob_calm / hours
    p_calm = _wilcoxon(raw_per_hour, rob_per_hour)
    a12_calm = _a12(raw_per_hour, rob_per_hour)

    # shifted: detection delay in ticks, with the declared imputation
    raw_d = [s["raw_delay"] for s in shifted]
    rob_d = [s["robust_delay"] for s in shifted]
    raw_imputed = np.asarray(
        [float(N_TICKS) if r is None else float(r) for r in raw_d],
        dtype=float)
    rob_imputed = np.asarray(
        [float(N_TICKS) if r is None else float(r) for r in rob_d],
        dtype=float)
    p_delay = _wilcoxon(raw_imputed, rob_imputed)
    a12_delay = _a12(raw_imputed, rob_imputed)
    n_raw_detected = sum(1 for x in raw_d if x is not None)
    n_rob_detected = sum(1 for x in rob_d if x is not None)

    summary = {
        "dataset": f"synthetic tick, Student-t df={args.noise_df:.1f}",
        "n_ticks": N_TICKS,
        "change_at": CHANGE_AT,
        "n_seeds": n_seeds,
        "calm": {
            "raw_episodes": _summary([float(x) for x in raw_calm]),
            "robust_episodes": _summary([float(x) for x in rob_calm]),
            "raw_per_hour": float(np.median(raw_per_hour)),
            "robust_per_hour": float(np.median(rob_per_hour)),
            "wilcoxon_p": p_calm,
            "a12": a12_calm,
        },
        "shift": {
            "n_raw_detected": n_raw_detected,
            "n_robust_detected": n_rob_detected,
            "raw_delay": _summary(raw_d),
            "robust_delay": _summary(rob_d),
            "raw_delay_imputed": _summary(
                [float(v) for v in raw_imputed]),
            "robust_delay_imputed": _summary(
                [float(v) for v in rob_imputed]),
            "imputation_ticks": N_TICKS,
            "wilcoxon_p": p_delay,
            "a12": a12_delay,
        },
        "wall_time_s": dt,
        "per_seed": {"calm": calm, "shifted": shifted},
    }
    out = args.out or (ROOT / "benchmarks" / "finance" / "drift_vs_noise.json")
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(json.dumps(summary, indent=2) + "\n", encoding="utf-8")

    print(f"synthetic tick, Student-t df={args.noise_df:.1f}, {n_seeds} seeds")
    print("calm (no shift): episodes per hour")
    print(f"  raw    median {summary['calm']['raw_per_hour']:.2f}")
    print(f"  robust median {summary['calm']['robust_per_hour']:.2f}")
    print(f"  Wilcoxon p {p_calm:.4f}, A12 {a12_calm:.3f}")
    print("shift (drift 0 -> 0.002): detection delay in ticks")
    print(f"  detected: raw {n_raw_detected}/{n_seeds}, "
          f"robust {n_rob_detected}/{n_seeds}")
    print(f"  raw    median {summary['shift']['raw_delay']['median']} "
          f"IQR {summary['shift']['raw_delay']['iqr']}")
    print(f"  robust median {summary['shift']['robust_delay']['median']} "
          f"IQR {summary['shift']['robust_delay']['iqr']}")
    print(f"  Wilcoxon p {p_delay:.4f}, A12 {a12_delay:.3f} "
          f"(imputed {N_TICKS} ticks for no alarm)")
    print(f"wall time {dt:.1f} s")
    print(f"written: {out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
